// Occupant-facing AI transparency, per the IMDA Model AI Governance Framework
// for Agentic AI (end-user responsibility: tell people they are dealing with an
// AI agent, what it can and cannot do, and how to reach a human).

export function AiAssistedLabel() {
  return (
    <span
      className="ai-label"
      title="Generated by an AI assistant. It can make mistakes."
    >
      AI-assisted
    </span>
  );
}

type AiDisclosureProps = {
  variant: "chat" | "report" | "track";
};

const DISCLOSURE: Record<AiDisclosureProps["variant"], string> = {
  chat: "You are chatting with an AI assistant, not a person. Answers come from the building's approved documents and can still be wrong or incomplete, so check anything important with the facilities team. It only logs a report after you confirm, and the facilities team reviews urgent or uncertain reports.",
  report:
    "Your report is saved as written. An AI assistant then suggests its category and priority, and the facilities team can review and change them.",
  track:
    "Reports are sorted and prioritised with AI assistance. The facilities team reviews them and sets the status shown here.",
};

export default function AiDisclosure({ variant }: AiDisclosureProps) {
  return (
    <aside className="ai-disclosure" aria-label="About AI use">
      <AiAssistedLabel />
      <p>
        {DISCLOSURE[variant]} For emergencies such as fire, injury or someone
        trapped in a lift, do not use this service: call emergency services or
        building security directly.
      </p>
    </aside>
  );
}
